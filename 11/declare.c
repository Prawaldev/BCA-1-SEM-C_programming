//wap to declare and initialize variables
#include <stdio.h>

int main() {
    int a = 5;
    float b = 3.14;
    char c = 'A';
    double d = 2.71828;
    long e = 1000000;

    printf("Integer: %d\n", a);
    printf("Float: %f\n", b);
    printf("Character: %c\n", c);
    printf("Double: %lf\n", d);
    printf("Long: %ld\n", e);

    return 0;
}